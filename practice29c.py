class calculator:
    def add(self,a,b):
        result=a+b
        print(f"The Sum is:{result}")
    def substract(self,c,d):
        result=c-d
        print(f"The Difference is:{result}")
    def multiply(self,e,f):
        result=e*f
        print(f"The Product is:{result}")
cal=calculator()
cal.add(10,5)
cal.substract(15,6) 
cal.multiply(20,10) 